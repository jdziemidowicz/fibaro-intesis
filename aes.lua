-- GF(2^8) multiply-by-2 (irreducible polynomial 0x11B)
local function xtime(a)
    return ((a << 1) ~ (a >= 0x80 and 0x1B or 0x00)) & 0xFF
end

-- GF(2^8) multiply (used to build InvMixColumns tables)
local function gmul(a, b)
    local p = 0
    for _ = 1, 8 do
        if b & 1 ~= 0 then p = p ~ a end
        local hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi ~= 0 then a = a ~ 0x1B end
        b = b >> 1
    end
    return p
end

-- Precomputed multiplication tables for InvMixColumns
local mul2  = {}
local mul9  = {}
local mul11 = {}
local mul13 = {}
local mul14 = {}
for i = 0, 255 do
    mul2[i]  = xtime(i)
    mul9[i]  = gmul(9,  i)
    mul11[i] = gmul(11, i)
    mul13[i] = gmul(13, i)
    mul14[i] = gmul(14, i)
end

-- AES-128 key schedule: returns array rk[0..10], each a 16-byte flat array
local RCON = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36}

local function aes_key_expand(key)
    -- key is a 16-byte string
    local w = {}          -- 44 words, 0-indexed; each word = {b0,b1,b2,b3}
    for i = 0, 3 do
        local base = i * 4
        w[i] = { key:byte(base+1), key:byte(base+2),
                 key:byte(base+3), key:byte(base+4) }
    end
    for i = 4, 43 do
        local temp = { w[i-1][1], w[i-1][2], w[i-1][3], w[i-1][4] }
        if i % 4 == 0 then
            -- RotWord then SubWord then XOR Rcon
            temp = { SBOX[temp[2]], SBOX[temp[3]], SBOX[temp[4]], SBOX[temp[1]] }
            temp[1] = temp[1] ~ RCON[i // 4]
        end
        local p = w[i-4]
        w[i] = { p[1]~temp[1], p[2]~temp[2], p[3]~temp[3], p[4]~temp[4] }
    end

    -- Pack into 11 round keys (each: 16-byte flat 1-indexed array)
    local rk = {}
    for r = 0, 10 do
        local k = {}
        for c = 0, 3 do
            local word = w[r*4 + c]
            k[c*4+1] = word[1]; k[c*4+2] = word[2]
            k[c*4+3] = word[3]; k[c*4+4] = word[4]
        end
        rk[r] = k
    end
    return rk
end

-- AddRoundKey
local function add_round_key(st, rk)
    for i = 1, 16 do st[i] = st[i] ~ rk[i] end
end

-- SubBytes (forward)
local function sub_bytes(st)
    for i = 1, 16 do st[i] = SBOX[st[i]] end
end

-- SubBytes (inverse)
local function inv_sub_bytes(st)
    for i = 1, 16 do st[i] = ISBOX[st[i]] end
end

-- ShiftRows (forward: row r shifted left by r)
-- Column-major layout: row r, col c  →  index c*4+r+1
local function shift_rows(st)
    local t
    -- Row 1 (indices 2,6,10,14): shift left 1
    t=st[2]; st[2]=st[6]; st[6]=st[10]; st[10]=st[14]; st[14]=t
    -- Row 2 (indices 3,7,11,15): shift left 2  (swap pairs)
    t=st[3]; st[3]=st[11]; st[11]=t
    t=st[7]; st[7]=st[15]; st[15]=t
    -- Row 3 (indices 4,8,12,16): shift left 3  (= rotate right 1)
    t=st[4]; st[4]=st[16]; st[16]=st[12]; st[12]=st[8]; st[8]=t
end

-- ShiftRows (inverse: row r shifted right by r)
local function inv_shift_rows(st)
    local t
    -- Row 1: shift right 1  (= rotate left 3)
    t=st[14]; st[14]=st[10]; st[10]=st[6]; st[6]=st[2]; st[2]=t
    -- Row 2: shift right 2  (swap pairs)
    t=st[3]; st[3]=st[11]; st[11]=t
    t=st[7]; st[7]=st[15]; st[15]=t
    -- Row 3: shift right 3  (= rotate left 1)
    t=st[4]; st[4]=st[8]; st[8]=st[12]; st[12]=st[16]; st[16]=t
end

-- MixColumns (forward): compact XOR form, avoids extra table lookups
local function mix_columns(st)
    for c = 0, 3 do
        local b = c*4+1
        local a0,a1,a2,a3 = st[b],st[b+1],st[b+2],st[b+3]
        local t = a0 ~ a1 ~ a2 ~ a3
        st[b]   = a0 ~ t ~ xtime(a0~a1)
        st[b+1] = a1 ~ t ~ xtime(a1~a2)
        st[b+2] = a2 ~ t ~ xtime(a2~a3)
        st[b+3] = a3 ~ t ~ xtime(a3~a0)
    end
end

-- InvMixColumns (inverse): uses precomputed GF tables
local function inv_mix_columns(st)
    for c = 0, 3 do
        local b = c*4+1
        local a0,a1,a2,a3 = st[b],st[b+1],st[b+2],st[b+3]
        st[b]   = mul14[a0] ~ mul11[a1] ~ mul13[a2] ~ mul9[a3]
        st[b+1] = mul9[a0]  ~ mul14[a1] ~ mul11[a2] ~ mul13[a3]
        st[b+2] = mul13[a0] ~ mul9[a1]  ~ mul14[a2] ~ mul11[a3]
        st[b+3] = mul11[a0] ~ mul13[a1] ~ mul9[a2]  ~ mul14[a3]
    end
end

-- Encrypt one 16-byte block (string) with pre-expanded round keys
local function aes_enc_block(pt, rk)
    local st = { pt:byte(1, 16) }
    add_round_key(st, rk[0])
    for r = 1, 9 do
        sub_bytes(st); shift_rows(st); mix_columns(st); add_round_key(st, rk[r])
    end
    sub_bytes(st); shift_rows(st); add_round_key(st, rk[10])
    return string.char(table.unpack(st))
end

-- Decrypt one 16-byte block (string) with pre-expanded round keys
local function aes_dec_block(ct, rk)
    local st = { ct:byte(1, 16) }
    add_round_key(st, rk[10])
    for r = 9, 1, -1 do
        inv_shift_rows(st); inv_sub_bytes(st)
        add_round_key(st, rk[r]); inv_mix_columns(st)
    end
    inv_shift_rows(st); inv_sub_bytes(st); add_round_key(st, rk[0])
    return string.char(table.unpack(st))
end

-- AES-128-ECB encrypt/decrypt (single 16-byte block)
function aes_ecb_encrypt(plaintext, key)
    return aes_enc_block(plaintext, aes_key_expand(key))
end

function aes_ecb_decrypt(ciphertext, key)
    return aes_dec_block(ciphertext, aes_key_expand(key))
end

-- AES-128-CBC encrypt (no PKCS7; input must be a multiple of 16 bytes)
local function _cbc_enc(plaintext, key, iv)
    local rk   = aes_key_expand(key)
    local out  = {}
    local prev = { iv:byte(1, 16) }
    for i = 1, #plaintext, 16 do
        local blk = { plaintext:byte(i, i+15) }
        for j = 1, 16 do blk[j] = blk[j] ~ prev[j] end
        local ct = aes_enc_block(string.char(table.unpack(blk)), rk)
        out[#out+1] = ct
        prev = { ct:byte(1, 16) }
    end
    return table.concat(out)
end

-- AES-128-CBC decrypt (no PKCS7; input must be a multiple of 16 bytes)
local function _cbc_dec(ciphertext, key, iv)
    local rk   = aes_key_expand(key)
    local out  = {}
    local prev = { iv:byte(1, 16) }
    for i = 1, #ciphertext, 16 do
        local blk = ciphertext:sub(i, i+15)
        local pt  = { aes_dec_block(blk, rk):byte(1, 16) }
        for j = 1, 16 do pt[j] = pt[j] ~ prev[j] end
        out[#out+1] = string.char(table.unpack(pt))
        prev = { blk:byte(1, 16) }
    end
    return table.concat(out)
end

local function increment_iv(iv)
    local b1 = ((iv:byte(1) + 1) & 0xFF)
    return md5(string.char(b1) .. iv:sub(2))
end

function aes_cbc_encrypt(plaintext, key, iv_ref)
    local cur_iv = iv_ref[1]
    iv_ref[1] = increment_iv(cur_iv)
    local pad = (-#plaintext) % 16
    if pad > 0 then plaintext = plaintext .. ("\0"):rep(pad) end
    return _cbc_enc(plaintext, key, cur_iv)
end

function aes_cbc_decrypt(ciphertext, key, iv_ref)
    local cur_iv = iv_ref[1]
    iv_ref[1] = increment_iv(cur_iv)
    return _cbc_dec(ciphertext, key, cur_iv)
end
